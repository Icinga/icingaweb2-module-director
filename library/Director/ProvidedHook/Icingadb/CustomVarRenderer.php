class CustomVarRenderer extends CustomVarRendererHook
{
    /** @var array Related datafield configuration */
    protected $fieldConfig = [];

    /** @var array Related custom variable configuration */
    protected $customVariableConfig = [];

    /**
     * Datalist entries, keyed by the owning property's own full scope (see
     * ownScopeKey()), then entry_name. Two properties can share a key_name and
     * still have unrelated datalists, so never key or look this up by name alone.
     *
     * @var array
     */
    protected $datalistMaps = [];

    /** @var array Related dictionary field names */
    protected $dictionaryNames = [];

    /** @var array Related dictionary field names */
    protected $customPropertyDictionaries = [];

    /**
     * Dictionary child configuration, keyed by full ancestor scope (see scopeKey())
     * then by child key_name. Two unrelated dictionaries can share a child name with
     * different sensitivity, so never key or look this up by name alone.
     *
     * @var array
     */
    protected $dictionaryChildConfig = [];

    /**
     * Sensitive item positions within fixed-array properties, keyed by ancestor
     * scope (see scopeKey()) then position, e.g. ['ssh_args' => ['3' => true]].
     * Same scoping as $dictionaryChildConfig, same reason.
     *
     * @var array
     */
    protected $sensitiveArrayItems = [];

    protected $dictionaryLevel = 0;

    /**
     * Whether prefetchForObject() failed, none of the config above can be trusted then,
     * so a value must render masked rather than fall back to raw
     *
     * @var bool
     */
    protected $prefetchFailed = false;

    /** @var HtmlElement Table for dictionary fields */
    private $dictionaryTable;

    /** @var HtmlElement Table body for dictionary fields */
    private $dictionaryBody;

    /**
     * Get a database connection to the director database
     *
     * @return Db
     *
     * @throws ConfigurationError
     */
    protected function db(): Db
    {
        $resourceName = Config::module('director')->get('db', 'resource');
        if (! $resourceName) {
            throw new ConfigurationError('Cannot identify director db. No resource configured');
        }

        return Db::fromResourceName($resourceName);
    }

    /**
     * Whether $serviceName is one of the objects generated by the apply-for rule
     * iterating $hostVar
     *
     * Icinga 2 suffixes generated names with the value for "for (value in array)",
     * but with the key for "for (key => value in dict)". Mirrors the isApplyFor
     * check in IcingaService::renderObjectHeader().
     *
     * @param CustomVariable $hostVar
     * @param string $appliedServiceName
     * @param string $serviceName
     *
     * @return bool
     */
    private function isGeneratedApplyForServiceName(
        CustomVariable $hostVar,
        string $appliedServiceName,
        string $serviceName
    ): bool {
        $suffixes = $hostVar instanceof CustomVariableDictionary
            ? $hostVar->listKeys()
            : $hostVar->getValue();

        foreach ($suffixes as $suffix) {
            if ($appliedServiceName . $suffix === $serviceName) {
                return true;
            }
        }

        return false;
    }

    public function prefetchForObject(Model $object): bool
    {
        try {
            if ($object instanceof Host) {
                $host = $object;
                $service = null;
            } elseif ($object instanceof Service) {
                $host = $object->host;
                $service = $object;
            } else {
                return false;
            }

            $db = $this->db();

            try {
                $directorHostObj = IcingaHost::load($host->name, $db);
                $directorServiceObj = null;
                if ($service !== null) {
                    $serviceOrigin = ['direct', 'applied', 'inherited', 'service-set'];
                    $serviceName = $service->name;
                    $i = 0;
                    do {
                        if ($i > 3) {
                            Logger::error("Failed to find service '%s' on host '%s'", $serviceName, $host->name);

                            return false;
                        } elseif ($serviceOrigin[$i] === 'direct') {
                            $directorServiceObj = IcingaService::loadOptional([
                                'host_id'     => $directorHostObj->get('id'),
                                'object_name' => $serviceName
                            ], $db);
                        } elseif ($serviceOrigin[$i] === 'inherited') {
                            $templateResolver =  new IcingaTemplateResolver($directorHostObj);

                            $parentIds = $templateResolver->listParentIds();

                            $query = $db->getDbAdapter()->select()->from('icinga_service')
                                ->where('object_name = ?', $serviceName)
                                ->where('host_id IN (?)', $parentIds);

                            $directorServices = IcingaService::loadAll(
                                $db,
                                $query,
                                'object_name'
                            );

                            $directorServiceObj = current($directorServices);
                        } elseif ($serviceOrigin[$i] === 'applied') {
                            $appliedFilterQuery = IcingaHostAppliedServicesTable::load($directorHostObj)->getQuery();

                            foreach ($appliedFilterQuery->fetchAll() as $appliedService) {
                                if ($appliedService->apply_for === null) {
                                    $isAppliedService = $appliedService->name === $serviceName;
                                } else {
                                    $hostVar = $directorHostObj->vars()->get((substr($appliedService->apply_for, 10)));
                                    $isAppliedService = $hostVar !== null
                                        && $this->isGeneratedApplyForServiceName(
                                            $hostVar,
                                            $appliedService->name,
                                            $serviceName
                                        );
                                }

                                if (! $isAppliedService) {
                                    continue;
                                }

                                $query = $db->getDbAdapter()->select()->from('icinga_service')
                                    ->where('object_name = ?', $appliedService->name)
                                    ->where("object_type = 'apply'")
                                    ->where('assign_filter = ?', $appliedService->assign_filter);

                                $directorAppliedServices = IcingaService::loadAll(
                                    $db,
                                    $query,
                                    'object_name'
                                );

                                $directorServiceObj = current($directorAppliedServices);

                                break;
                            }
                        } elseif ($serviceOrigin[$i] === 'service-set') {
                            $templateResolver =  new IcingaTemplateResolver($directorHostObj);

                            $hostServiceSets = $directorHostObj->fetchServiceSets()
                                + AppliedServiceSetLoader::fetchForHost($directorHostObj);

                            $parents = $templateResolver->fetchParents();

                            foreach ($parents as $parent) {
                                $hostServiceSets += $parent->fetchServiceSets();
                                $hostServiceSets += AppliedServiceSetLoader::fetchForHost($parent);
                            }

                            foreach ($hostServiceSets as $hostServiceSet) {
                                foreach ($hostServiceSet->getServiceObjects() as $setServiceObject) {
                                    if ($setServiceObject->getObjectName() === $serviceName) {
                                        $directorServiceObj = $setServiceObject;

                                        break 2;
                                    }
                                }
                            }
                        }

                        $i++;
                    } while (! $directorServiceObj);
                }
            } catch (NotFoundError $_) {
                if ($service !== null) {
                    Logger::error("Failed to find service '%s' on host '%s'", $service->name, $host->name);
                } else {
                    Logger::error('Failed to find host %s', $host->name);
                }

                return false;
            }

            if ($service === null) {
                $fields = (new IcingaObjectFieldLoader($directorHostObj))->getFields();
            } else {
                $fields = (new IcingaObjectFieldLoader($directorServiceObj))->getFields();
            }

            $fieldsWithDataLists = [];
            foreach ($fields as $field) {
                $this->fieldConfig[$field->get('varname')] = [
                    'label'      => $field->get('caption'),
                    'group'      => $field->getCategoryName(),
                    'visibility' => $field->getSetting('visibility')
                ];

                if ($field->get('datatype') === 'Icinga\Module\Director\DataType\DataTypeDatalist') {
                    $fieldsWithDataLists[$field->get('id')] = $field;
                } elseif ($field->get('datatype') === 'Icinga\Module\Director\DataType\DataTypeDictionary') {
                    $this->dictionaryNames[] = $field->get('varname');
                }
            }

            if (! empty($fieldsWithDataLists)) {
                if ($this->db()->getDbType() === 'pgsql') {
                    $joinCondition = 'CAST(dds.setting_value AS INTEGER) = dde.list_id';
                } else {
                    $joinCondition = 'dds.setting_value = dde.list_id';
                }

                $dataListEntries = $db->select()->from(
                    ['dds' => 'director_datafield_setting'],
                    [
                        'dds.datafield_id',
                        'dde.entry_name',
                        'dde.entry_value'
                    ]
                )->join(
                    ['dde' => 'director_datalist_entry'],
                    $joinCondition,
                    []
                )->where('dds.datafield_id', array_keys($fieldsWithDataLists))
                    ->where('dds.setting_name', 'datalist_id');

                foreach ($dataListEntries as $dataListEntry) {
                    $field = $fieldsWithDataLists[$dataListEntry->datafield_id];
                    $this->datalistMaps[$field->get('varname')][$dataListEntry->entry_name]
                        = $dataListEntry->entry_value;
                }
            }

            if ($service === null) {
                $customProperties = $this->getObjectCustomProperties($directorHostObj);
            } else {
                $customProperties = $this->getObjectCustomProperties($directorServiceObj);
            }

            if (empty($customProperties)) {
                return true;
            }

            foreach ($customProperties as $customProperty) {
                $propertyName = $customProperty['key_name'];
                $this->customVariableConfig[$propertyName] = [
                    'label'      => $customProperty['label'],
                    'value_type' => $customProperty['value_type'],
                ];
                if (isset($customProperty['category'])) {
                    $this->customVariableConfig[$propertyName]['group'] = $customProperty['category'];
                }

                if ($customProperty['value_type'] === 'sensitive') {
                    $this->customVariableConfig[$propertyName]['visibility'] = 'hidden';
                }

                if (str_ends_with($customProperty['value_type'], '-dictionary')) {
                    $this->dictionaryNames[] = $propertyName;
                }
            }

            $this->loadNestedPropertyConfig($db, $customProperties);

            return true;
        } catch (Throwable $e) {
            Logger::error("%s\n%s", $e, $e->getTraceAsString());
            $this->prefetchFailed = true;

            // Stay registered anyway, or Icinga DB never asks us to render at all and
            // a sensitive value shows up raw instead of masked.
            return true;
        }
    }

    private function valueTypeOrderExpr(Db $db, array $types): string
    {
        if ($db->isPgsql()) {
            $cases = [];
            foreach ($types as $i => $type) {
                $cases[] = "WHEN '$type' THEN " . ($i + 1);
            }
            return 'CASE dp.value_type ' . implode(' ', $cases) . ' ELSE ' . (count($types) + 1) . ' END';
        }

        return "FIELD(dp.value_type, '" . implode("', '", $types) . "')";
    }

    /**
     * Get custom properties for the host.
     *
     * @param IcingaObject $object The host or service to fetch properties for
     *
     * @return array
     */
    protected function getObjectCustomProperties(IcingaObject $object): array
    {
        if ($object->get('uuid') === null) {
            return [];
        }

        $type = $object->getShortTableName();
        $parents = $object->listAncestorIds();

        $uuids = [];
        $db = $this->db();

        $objectClass = DbObjectTypeRegistry::classByType($type);
        foreach ($parents as $parent) {
            $uuids[] = $objectClass::loadWithAutoIncId($parent, $db)->get('uuid');
        }

        $uuids[] = $object->get('uuid');
        $dbAdapter = $db->getDbAdapter();
        $query = $dbAdapter
            ->select()
            ->from(
                ['dp' => 'director_property'],
                [
                    'key_name' => 'dp.key_name',
                    'uuid' => 'dp.uuid',
                    'category' => 'cpc.category_name',
                    $type . '_uuid' => 'iop.' . $type . '_uuid',
                    'value_type' => 'dp.value_type',
                    'label' => 'dp.label',
                    'children' => 'COUNT(cdp.uuid)'
                ]
            )
            ->join(['iop' => "icinga_$type" . '_property'], 'dp.uuid = iop.property_uuid', [])
            ->joinLeft(['cdp' => 'director_property'], 'cdp.parent_uuid = dp.uuid', [])
            ->joinLeft(['cpc' => 'director_datafield_category'], 'dp.category_id = cpc.id', [])
            ->where('iop.' . $type . '_uuid IN (?)', DbUtil::quoteBinaryCompat($uuids, $dbAdapter))
            ->group([
                'dp.uuid',
                'dp.key_name',
                'dp.value_type',
                'dp.label',
                'cpc.category_name',
                'iop.' . $type . '_uuid'
            ])
            ->order($this->valueTypeOrderExpr($db, [
                'string',
                'number',
                'bool',
                'datalist-strict',
                'datalist-non-strict',
                'dynamic-array',
                'fixed-dictionary',
                'dynamic-dictionary'
            ]))
            ->order('children')
            ->order('key_name');

        $result = [];

        foreach ($db->getDbAdapter()->fetchAll($query, fetchMode: PDO::FETCH_ASSOC) as $row) {
            $result[$row['key_name']] = $row;
        }

        return $result;
    }

    /**
     * Build the scope key a property's metadata is stored and looked up under
     *
     * Chains every ancestor into the key instead of just the immediate parent, so
     * two properties can only collide if they share their entire ancestor path.
     *
     * @param ?string $outerScope
     * @param string $key
     *
     * @return string
     */
    protected function scopeKey(?string $outerScope, string $key): string
    {
        return $outerScope === null ? $key : $outerScope . "\0" . $key;
    }

    /**
     * Scope key for a property's own identity, not its ancestor path
     *
     * dictionaryChildConfig and sensitiveArrayItems key by the parent's scope plus
     * the child's key_name. A datalist attaches to the property itself though, so
     * we need one more level, chaining the key onto its own ancestor scope.
     *
     * @param string $key
     * @param ?string $parentKey
     * @param ?string $grandparentKey
     *
     * @return string
     */
    protected function ownScopeKey(string $key, ?string $parentKey, ?string $grandparentKey = null): string
    {
        if ($parentKey === null) {
            return $key;
        }

        return $this->scopeKey($this->scopeKey($grandparentKey, $parentKey), $key);
    }

    /**
     * Load dictionary child, sensitive-array and datalist metadata for the object's
     * own property tree
     *
     * Custom properties nest at most one level deep, so this only walks 2 generations
     * below the object's top level properties, never the whole director_property table.
     *
     * @param Db $db
     * @param array $customProperties Top level custom properties of the rendered
     *                                 object, as returned by getObjectCustomProperties()
     *
     * @return void
     */
    private function loadNestedPropertyConfig(Db $db, array $customProperties): void
    {
        $dbAdapter = $db->getDbAdapter();

        // uuid (raw binary) => ['key_name' => ..., 'value_type' => ..., 'scope' => ?string]
        $frontier = [];
        foreach ($customProperties as $property) {
            $frontier[DbUtil::binaryResult($property['uuid'])] = [
                'key_name'   => $property['key_name'],
                'value_type' => $property['value_type'],
                'scope'      => null,
            ];
        }

        $allProperties = $frontier;

        for ($depth = 0; $depth < 2 && ! empty($frontier); $depth++) {
            $query = $dbAdapter->select()
                ->from('director_property', ['uuid', 'parent_uuid', 'key_name', 'label', 'value_type'])
                ->where('parent_uuid IN (?)', DbUtil::quoteBinaryCompat(array_keys($frontier), $dbAdapter));

            $children = [];
            foreach ($dbAdapter->fetchAll($query, [], PDO::FETCH_ASSOC) as $row) {
                $row = DbUtil::normalizeRow($row);
                $parent = $frontier[$row['parent_uuid']] ?? null;
                if ($parent === null) {
                    continue;
                }

                $scope = $this->scopeKey($parent['scope'], $parent['key_name']);

                if ($parent['value_type'] === 'fixed-array' && $row['value_type'] === 'sensitive') {
                    $this->sensitiveArrayItems[$scope][$row['key_name']] = true;
                }

                if (in_array($parent['value_type'], ['fixed-dictionary', 'dynamic-dictionary'], true)) {
                    $this->customPropertyDictionaries[$parent['key_name']][$row['key_name']] = $row['label'];

                    $childConfig = ['label' => $row['label'], 'value_type' => $row['value_type']];
                    if ($row['value_type'] === 'sensitive') {
                        $childConfig['visibility'] = 'hidden';
                    }

                    $this->dictionaryChildConfig[$scope][$row['key_name']] = $childConfig;
                }

                $children[$row['uuid']] = [
                    'key_name'   => $row['key_name'],
                    'value_type' => $row['value_type'],
                    'scope'      => $scope,
                ];
            }

            $allProperties += $children;
            $frontier = $children;
        }

        $this->loadDatalistEntries($dbAdapter, $allProperties);
    }

    /**
     * Load datalist captions for every property in $properties that has one attached
     *
     * A datalist can sit on a root property, on a dynamic-array (one shared list for
     * every item), or on one named position of a fixed-array. Each of those is its own
     * director_property row, so we key by that property's own full scope instead of
     * its bare key_name, or two unrelated properties sharing a name would stomp on
     * each other's captions.
     *
     * @param Zend_Db_Adapter_Abstract|Adapter $dbAdapter
     * @param array $properties Uuid (raw binary) => ['key_name' => ..., 'scope' => ?string, ...]
     *
     * @return void
     */
    private function loadDatalistEntries($dbAdapter, array $properties): void
    {
        if (empty($properties)) {
            return;
        }

        $query = $dbAdapter->select()->from(
            ['dpd' => 'director_property_datalist'],
            [
                'property_uuid' => 'dpd.property_uuid',
                'entry_name'    => 'dde.entry_name',
                'entry_value'   => 'dde.entry_value',
            ]
        )->join(
            ['dd' => 'director_datalist'],
            'dd.uuid = dpd.list_uuid',
            []
        )->join(
            ['dde' => 'director_datalist_entry'],
            'dd.id = dde.list_id',
            []
        )->where('dpd.property_uuid IN (?)', DbUtil::quoteBinaryCompat(array_keys($properties), $dbAdapter));

        foreach ($dbAdapter->fetchAll($query, [], PDO::FETCH_ASSOC) as $row) {
            $row = DbUtil::normalizeRow($row);
            $property = $properties[$row['property_uuid']] ?? null;
            if ($property === null) {
                continue;
            }

            $scope = $this->scopeKey($property['scope'], $property['key_name']);
            $this->datalistMaps[$scope][$row['entry_name']] = $row['entry_value'];
        }
    }

    /**
     * Look up dictionary-child config for $key under parent $parentKey, if any
     *
     * @param string $key
     * @param ?string $parentKey
     * @param ?string $grandparentKey Set when $parentKey is itself nested one level deep
     *
     * @return ?array
     */
    private function dictionaryChildConfigFor(string $key, ?string $parentKey, ?string $grandparentKey = null): ?array
    {
        if ($parentKey === null) {
            return null;
        }

        return $this->dictionaryChildConfig[$this->scopeKey($grandparentKey, $parentKey)][$key] ?? null;
    }

    /**
     * Whether $key, scoped under $parentKey/$grandparentKey, is a *-dictionary
     *
     * dictionaryNames is a flat, unscoped list of top-level dictionary names, so it
     * only works when $key is top-level itself ($parentKey === null). A nested child
     * can share its name with an unrelated top-level dictionary elsewhere in the same
     * property tree, so nested lookups go through the scoped dictionaryChildConfig
     * instead.
     *
     * @param string $key
     * @param ?string $parentKey
     * @param ?string $grandparentKey
     *
     * @return bool
     */
    private function isDictionaryValueType(string $key, ?string $parentKey, ?string $grandparentKey = null): bool
    {
        if ($parentKey === null) {
            return in_array($key, $this->dictionaryNames, true);
        }

        $valueType = $this->dictionaryChildConfigFor($key, $parentKey, $grandparentKey)['value_type'] ?? null;

        return $valueType !== null && str_ends_with($valueType, '-dictionary');
    }

    /**
     * Render a custom variable key as a label, with its full key as a title tooltip
     *
     * @param string $key
     * @param ?string $parentKey
     * @param ?string $grandparentKey
     *
     * @return ?ValidHtml
     */
    public function renderCustomVarKey(string $key, ?string $parentKey = null, ?string $grandparentKey = null)
    {
        try {
            $label = $this->fieldConfig[$key]['label']
                ?? $this->dictionaryChildConfigFor($key, $parentKey, $grandparentKey)['label']
                ?? $this->customVariableConfig[$key]['label']
                ?? null;
            if ($label === null) {
                return null;
            }

            $span = new HtmlElement(
                'span',
                Attributes::create(['title' => $label . " [$key]"]),
                Text::create($label)
            );

            // Icingadb tags a raw array itself but can't see inside our pre-rendered
            // dictionary HTML, so only the variable's own row needs tagging here.
            if ($parentKey === null && $this->isDictionaryValueType($key, null)) {
                return $this->decorateArrayOrDictionaryName($span, true);
            }

            return $span;
        } catch (Throwable $e) {
            Logger::error("%s\n%s", $e, $e->getTraceAsString());
        }

        return null;
    }

    /**
     * Render one custom variable value, masking it if it's sensitive
     *
     * @param string $key
     * @param mixed $value
     * @param ?string $parentKey
     * @param ?string $grandparentKey
     *
     * @return ?ValidHtml
     */
    public function renderCustomVarValue(
        string $key,
        $value,
        ?string $parentKey = null,
        ?string $grandparentKey = null
    ): mixed {
        $childConfig = $this->dictionaryChildConfigFor($key, $parentKey, $grandparentKey);

        if (! (isset($this->fieldConfig[$key]) || $childConfig !== null || isset($this->customVariableConfig[$key]))) {
            // No config means "not ours" only when prefetch actually ran. If it failed,
            // this config is empty regardless of what the var actually is, so masking
            // is the only safe answer here.
            return $this->prefetchFailed ? '***' : null;
        }

        try {
            if (isset($this->fieldConfig[$key]) && $this->fieldConfig[$key]['visibility'] === 'hidden') {
                return '***';
            }

            $visibility = $childConfig['visibility'] ?? $this->customVariableConfig[$key]['visibility'] ?? null;
            if ($visibility === 'hidden') {
                return '***';
            }

            if (is_array($value) && ! isset($this->customPropertyDictionaries[$key])) {
                $renderedValue = [];
                // A shared datalist can sit on the array itself, or a fixed-array
                // position can have its own. Try the position first, then the array.
                $arrayScope = $this->ownScopeKey($key, $parentKey, $grandparentKey);
                foreach ($value as $k => $v) {
                    if (isset($this->sensitiveArrayItems[$arrayScope][$k])) {
                        $renderedValue[$k] = '***';

                        continue;
                    }

                    $itemScope = $this->scopeKey($arrayScope, (string) $k);

                    if (is_array($v)) {
                        // A fixed-array position can itself be a list-valued datalist (a
                        // datalist whose item type is a dynamic-array), map each picked
                        // entry through that position's own list, not the array's shared one.
                        $renderedValue[$k] = isset($this->datalistMaps[$itemScope])
                            ? $this->renderDatalistArrayItems($this->datalistMaps[$itemScope], $v)
                            : $v;

                        continue;
                    }

                    $caption = null;
                    if (is_string($v)) {
                        $caption = $this->datalistMaps[$itemScope][$v] ?? $this->datalistMaps[$arrayScope][$v] ?? null;
                    }

                    $renderedValue[$k] = $caption !== null ? $this->captionSpan($caption, $v) : $v;
                }

                return $renderedValue;
            }

            $ownScope = $this->ownScopeKey($key, $parentKey, $grandparentKey);
            if (is_string($value) && isset($this->datalistMaps[$ownScope][$value])) {
                return $this->captionSpan($this->datalistMaps[$ownScope][$value], $value);
            } elseif ($value !== null && $this->isDictionaryValueType($key, $parentKey, $grandparentKey)) {
                return $this->renderDictionaryVal($key, (array) $value);
            }

            return null;
        } catch (Throwable $e) {
            Logger::error("%s\n%s", $e, $e->getTraceAsString());

            // This key is one of ours (checked above), we just failed to work out
            // how to render it. Mask it, showing it raw would defeat sensitive fields.
            return '***';
        }
    }

    /**
     * Map every string entry of a list-valued datalist through its own caption map
     *
     * @param array $map    entry_name => caption, scoped to this one position
     * @param array $values raw picks stored at this position
     *
     * @return array
     */
    private function renderDatalistArrayItems(array $map, array $values): array
    {
        $rendered = [];
        foreach ($values as $k => $v) {
            $rendered[$k] = is_string($v) && isset($map[$v]) ? $this->captionSpan($map[$v], $v) : $v;
        }

        return $rendered;
    }

    /**
     * Wrap a raw value in a span showing its datalist caption, raw value as tooltip
     *
     * @param string $caption
     * @param string $rawValue
     *
     * @return ValidHtml
     */
    private function captionSpan(string $caption, string $rawValue): ValidHtml
    {
        return new HtmlElement(
            'span',
            Attributes::create(['title' => "$caption [$rawValue]"]),
            Text::create($caption)
        );
    }

    public function identifyCustomVarGroup(string $key): ?string
    {
        if (isset($this->fieldConfig[$key]['group'])) {
            return $this->fieldConfig[$key]['group'];
        } elseif (isset($this->customVariableConfig[$key]['group'])) {
            return $this->customVariableConfig[$key]['group'];
        }

        return null;
    }

    /**
     * Render the dictionary value
     *
     * @param string $key
     * @param array $value
     *
     * @return ?ValidHtml
     */
    protected function renderDictionaryVal(string $key, array $value): ?ValidHtml
    {
        if ($this->dictionaryLevel > 0) {
            $numItems = count($value);
            $label = $this->renderCustomVarKey($key) ?? $key;

            $this->dictionaryBody->addHtml(
                new HtmlElement(
                    'tr',
                    Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                    new HtmlElement('th', null, Html::wantHtml($label)),
                    new HtmlElement(
                        'td',
                        null,
                        Text::create(sprintf(tp('%d item', '%d items', $numItems), $numItems))
                    )
                )
            );
        } else {
            $this->dictionaryTable = new HtmlElement(
                'table',
                Attributes::create(['class' => ['custom-var-table', 'name-value-table']])
            );

            $this->dictionaryBody = new HtmlElement('tbody');
        }

        $this->dictionaryLevel++;

        foreach ($value as $k => $val) {
            if (is_array($val) || is_object($val)) {
                // $val may be a genuine nested array (fixed-/dynamic-array), not a nested
                // dictionary - mask any sensitive positions it holds using its own key ($k)
                // before its items are iterated below by position/child key, since those
                // per-item lookups have no way to recover the parent array's own key_name.
                if (is_array($val) && ! isset($this->customPropertyDictionaries[$k])) {
                    $val = $this->renderCustomVarValue($k, $val, $key) ?? $val;
                }

                $val = (array) $val;

                // User picked entry names have no schema to check, but every entry of a
                // dynamic-dictionary is itself a dictionary, never a plain list.
                $isDynamicDictionary = ($this->customVariableConfig[$key]['value_type'] ?? null)
                    === 'dynamic-dictionary';
                $isDictionary = $isDynamicDictionary || $this->isDictionaryValueType($k, $key);

                $ownLabel = $this->renderCustomVarKey($k, $key) ?? Html::wantHtml($k);

                // Only a genuine list of positions gets the same treatment as any other
                // array. A schema-less field with named entries (an old style data field,
                // say) still needs its own keys shown as is, not as list positions.
                if (! $isDictionary && array_is_list($val)) {
                    $this->renderArrayVal($ownLabel, $val);

                    continue;
                }

                $numChildItems = count($val);
                $ownLabel = $this->decorateArrayOrDictionaryName($ownLabel, $isDictionary);

                $this->dictionaryBody->addHtml(
                    new HtmlElement(
                        'tr',
                        Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                        new HtmlElement('th', null, Html::wantHtml($ownLabel)),
                        new HtmlElement(
                            'td',
                            null,
                            Text::create(sprintf(tp('%d item', '%d items', $numChildItems), $numChildItems))
                        )
                    )
                );

                // A fixed-dictionary declares each entry by name, so its fields are scoped
                // under that entry. A dynamic-dictionary's entries are picked by the user
                // though, so its fields are declared once on the dictionary itself instead.
                if ($isDynamicDictionary) {
                    $fieldParentKey = $key;
                    $fieldGrandparentKey = null;
                } else {
                    $fieldParentKey = $k;
                    $fieldGrandparentKey = $key;
                }

                $this->dictionaryLevel++;
                foreach ($val as $childKey => $childVal) {
                    $childVal = $this->renderCustomVarValue($childKey, $childVal, $fieldParentKey, $fieldGrandparentKey)
                        ?? $childVal;
                    $label = $this->renderCustomVarKey($childKey, $fieldParentKey, $fieldGrandparentKey) ?? $childKey;

                    // A masked or datalist-mapped value is always a string or ValidHtml,
                    // never an array, no matter what the schema says $childKey is. So we
                    // check the actual value before recursing into it. The Array vs
                    // Dictionary label still comes from the schema, scoped correctly,
                    // since $childKey alone can collide with an unrelated dictionary
                    // elsewhere in the property tree (e.g. a schema child sharing its own
                    // parent's key_name).
                    if (! $childVal instanceof ValidHtml && (is_array($childVal) || is_object($childVal))) {
                        $isDictionaryChild = $this
                            ->isDictionaryValueType($childKey, $fieldParentKey, $fieldGrandparentKey);
                        $this->renderArrayVal($label, (array) $childVal, $isDictionaryChild ? $childKey : null);
                    } else {
                        $this->dictionaryBody->addHtml(
                            new HtmlElement(
                                'tr',
                                Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                                new HtmlElement('th', null, Html::wantHtml(
                                    $label
                                )),
                                new HtmlElement('td', null, Html::wantHtml($childVal))
                            )
                        );
                    }
                }

                $this->dictionaryLevel--;
            } else {
                $this->dictionaryBody->addHtml(
                    new HtmlElement(
                        'tr',
                        Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                        new HtmlElement('th', null, $this->renderCustomVarKey($k, $key) ?? Html::wantHtml($k)),
                        new HtmlElement(
                            'td',
                            null,
                            Html::wantHtml($this->renderCustomVarValue($k, $val, $key) ?? $val)
                        )
                    )
                );
            }
        }

        $this->dictionaryLevel--;

        if ($this->dictionaryLevel === 0) {
            // Icingadb's own custom var table only counts items itself for a plain
            // array value. We always hand back rendered HTML here instead (masking has
            // to happen while we still hold the raw value), so without this the root
            // row would show no item count at all, unlike a fixed-/dynamic-array.
            $numItems = count($value);

            return (new HtmlDocument())->addHtml(
                Text::create(sprintf(tp('%d item', '%d items', $numItems), $numItems)),
                $this->dictionaryTable->addHtml($this->dictionaryBody)
            );
        }

        return null;
    }

    /**
     * Append " (Array)" or " (Dictionary)" to a row label
     *
     * @param HtmlElement|ValidHtml|string $name
     * @param bool $isDictionary
     *
     * @return HtmlElement|HtmlDocument
     */
    private function decorateArrayOrDictionaryName($name, bool $isDictionary)
    {
        $suffix = $isDictionary ? ' (Dictionary)' : ' (Array)';

        if ($name instanceof HtmlElement) {
            $name->addHtml(Text::create($suffix));

            return $name;
        }

        return (new HtmlDocument())->addHtml(Html::wantHtml($name), Text::create($suffix));
    }

    /**
     * Render an array, if the passed key is a part of dictionary, then render as a dictionary
     *
     * @param HtmlElement|string $name
     * @param array $array
     * @param ?string $key Set when the value being rendered is actually a dictionary, so it
     *                     gets labeled "(Dictionary)" instead of "(Array)"
     *
     * @return void
     */
    protected function renderArrayVal($name, array $array, ?string $key = null): void
    {
        $numItems = count($array);
        $name = $this->decorateArrayOrDictionaryName($name, $key !== null);

        $this->dictionaryBody->addHtml(
            new HtmlElement(
                'tr',
                Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                new HtmlElement('th', null, Html::wantHtml($name)),
                new HtmlElement('td', null, Html::wantHtml(sprintf(tp('%d item', '%d items', $numItems), $numItems)))
            )
        );

        ++$this->dictionaryLevel;

        ksort($array);
        foreach ($array as $key => $value) {
            if (! $key instanceof HtmlElement) {
                $renderedKey = $this->renderCustomVarKey($key) ?? Html::wantHtml("[$key]");
            } else {
                $renderedKey = Html::wantHtml("[$key]");
            }

            if (! $value instanceof HtmlElement) {
                $renderedValue = Html::wantHtml($this->renderCustomVarValue($key, $value) ?? $value);
            } else {
                $renderedValue = Html::wantHtml($value);
            }

            $this->dictionaryBody->addHtml(
                new HtmlElement(
                    'tr',
                    Attributes::create(['class' => "level-{$this->dictionaryLevel}"]),
                    new HtmlElement('th', null, $renderedKey),
                    new HtmlElement('td', null, $renderedValue)
                )
            );
        }

        --$this->dictionaryLevel;
    }
}
